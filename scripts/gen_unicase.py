"""F-156: generates mojo/omxcore/unicase.mojo, the lower- and upper-case mappings of every Unicode code point below U+20000 exactly as DuckDB
applies them (utf8proc's simple mappings: 'İ' lowers to 'i', 'ß' uppers to 'ẞ', 'ſ' to 'S', no multi-character results).

    pixi run python scripts/gen_unicase.py

DuckDB is the oracle (the owner's rule: equal to DuckDB), so the tables are asked of DuckDB, not copied from a Unicode file. The mapping is stored as runs
(first code point, last code point, delta, step): a run of consecutive code points that move by one delta, or every other one (the Latin Extended pairs).
"""
import sys
from pathlib import Path

import duckdb

OUT = Path(__file__).resolve().parent.parent / "mojo" / "omxcore" / "unicase.mojo"
LIMIT = 0x20000


def table(con, fn):
    rows = con.execute(f"select i, {fn}(chr(i::INTEGER)) from range(1, {LIMIT}) r(i) where not (i between 55296 and 57343)").fetchall()
    out = {}
    for i, m in rows:
        if len(m) != 1:
            raise SystemExit(f"{fn}(chr({i})) is {m!r}: more than one character, the mapping is not simple")
        if ord(m) != i:
            out[i] = ord(m) - i
    return out


def runs(m):
    """Greedy runs of (first, last, delta, step) over the code points that change."""
    cps = sorted(m)
    out = []
    i = 0
    while i < len(cps):
        a = cps[i]
        d = m[a]
        # step 1 run
        j = i
        while j + 1 < len(cps) and cps[j + 1] == cps[j] + 1 and m[cps[j + 1]] == d:
            j += 1
        if j > i:
            out.append((a, cps[j], d, 1))
            i = j + 1
            continue
        # step 2 run
        j = i
        while j + 1 < len(cps) and cps[j + 1] == cps[j] + 2 and m[cps[j + 1]] == d:
            j += 1
        if j > i:
            out.append((a, cps[j], d, 2))
            i = j + 1
            continue
        out.append((a, a, d, 1))
        i += 1
    return out


def encode(rs):
    return ",".join(f"{a}:{b}:{d}:{s}" for a, b, d, s in rs)


def main():
    con = duckdb.connect()
    lo = runs(table(con, "lower"))
    up = runs(table(con, "upper"))
    src = '''"""Generated by scripts/gen_unicase.py from DuckDB %s: do not edit. Simple (one character to one character) case mappings below U+20000, as runs
`first:last:delta:step` (a step of 2 moves every other code point of the run)."""

comptime LOWER_RUNS = "%s"
comptime UPPER_RUNS = "%s"
''' % (duckdb.__version__, encode(lo), encode(up))
    OUT.write_text(src)
    print(f"{OUT}: {len(lo)} lower runs, {len(up)} upper runs, DuckDB {duckdb.__version__}")


if __name__ == "__main__":
    sys.exit(main())
